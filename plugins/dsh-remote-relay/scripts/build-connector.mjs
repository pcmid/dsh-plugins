// Builds launcher/dsh-remote.mjs: the connector CLI with the tunnel module inlined, so a remote
// computer needs only that one file (`curl -O <launcher>/dsh-remote.mjs`).
import { readFileSync, writeFileSync } from 'node:fs'

const read = (path) => readFileSync(new URL(`../${path}`, import.meta.url), 'utf8')
const tunnel = read('launcher/tunnel.js').replace(/^export (?=(?:async )?function |const |class )/gm, '')
const cli = read('bin/dsh-remote.mjs')
  .replace(/^#!.*\n/, '')
  .replace(/^import \{[^}]*\} from '\.\.\/launcher\/tunnel\.js'\n/m, '')
if (/from '\.\.\/launcher\/tunnel\.js'/.test(cli) || /^export /m.test(tunnel)) throw new Error('build-connector: unexpected module layout')
const banner = '#!/usr/bin/env node\n// Generated by scripts/build-connector.mjs from bin/dsh-remote.mjs and launcher/tunnel.js; do not edit.\n'
// The tunnel code comes first: the CLI calls main() while the module evaluates, so the tunnel's
// classes and constants must already be initialized.
writeFileSync(new URL('../launcher/dsh-remote.mjs', import.meta.url), `${banner}// ---- launcher/tunnel.js ----\n${tunnel}\n// ---- bin/dsh-remote.mjs ----\n${cli}`, { mode: 0o755 })
console.log('wrote launcher/dsh-remote.mjs')
