// Assemble client.js from the parts in client/: one Client module whose factory
// body is the concatenation of every client/*.js file in name order. The parts
// share that function scope; the last part returns `{ inject, apply }`.
//
//   node scripts/build-client.mjs          write client.js
//   node scripts/build-client.mjs --check  fail when client.js is stale
import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'))
const parts = readdirSync(join(root, 'client')).filter(name => name.endsWith('.js')).sort()

const indent = text => text.replace(/\n$/, '').split('\n').map(line => (line === '' ? '' : `    ${line}`)).join('\n')
const body = parts
  .map(name => `    // ---- client/${name} ----\n${indent(readFileSync(join(root, 'client', name), 'utf8'))}`)
  .join('\n\n')

const output = `// Generated by scripts/build-client.mjs from client/*.js — edit those files, then run \`npm run build\`.
window.__ModuleLoader__.load({
  id: '${pkg.name}',
  factory(require) {
    'use strict';
${body}
  },
});
`

const target = join(root, 'client.js')
if (process.argv.includes('--check')) {
  let current = ''
  try { current = readFileSync(target, 'utf8') } catch { /* missing counts as stale */ }
  if (current !== output) {
    console.error('client.js is stale: run `npm run build`')
    process.exit(1)
  }
} else {
  writeFileSync(target, output)
  console.log(`client.js ← ${parts.join(', ')}`)
}
